import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { Interface } from "ethers";
import hre from "hardhat";

import { CONTRACT_NAMES, type DeploymentManifest, DEPLOYMENTS_DIR, REPO_ROOT } from "./lib/protocol.js";

// Exports versioned ABI, event, and error artifacts from the compiled contracts:
//   contracts/deployments/abi/<Contract>.json      ABI per contract
//   contracts/deployments/abi/interface.json       event topics and error selectors
//   frontend/src/web3/generated/abis.ts            typed `as const` ABIs for viem/wagmi
//   frontend/src/web3/generated/localDeployment.ts local (31337) addresses only
//   backend/app/services/chain_events.py           event topics for receipt verification
// Sepolia addresses are never generated into source; they come from environment variables.

const HEADER = "Generated by contracts/scripts/export-artifacts.ts. Do not edit by hand.";

function camel(name: string): string {
  return name.charAt(0).toLowerCase() + name.slice(1).replace(/USDC/, "Usdc");
}

const abiDir = path.join(DEPLOYMENTS_DIR, "abi");
const frontendDir = path.join(REPO_ROOT, "frontend", "src", "web3", "generated");
const backendFile = path.join(REPO_ROOT, "backend", "app", "services", "chain_events.py");
await mkdir(abiDir, { recursive: true });
await mkdir(frontendDir, { recursive: true });

const events: { contract: string; name: string; signature: string; topic: string }[] = [];
const errors: { contract: string; name: string; signature: string; selector: string }[] = [];
const tsAbis: string[] = [`// ${HEADER}`, ""];

for (const name of CONTRACT_NAMES) {
  const artifact = await hre.artifacts.readArtifact(name);
  await writeFile(path.join(abiDir, `${name}.json`), `${JSON.stringify(artifact.abi, null, 2)}\n`);
  tsAbis.push(`export const ${camel(name)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`, "");

  const iface = new Interface(artifact.abi);
  iface.forEachEvent((event) => {
    events.push({ contract: name, name: event.name, signature: event.format("sighash"), topic: event.topicHash });
  });
  iface.forEachError((error) => {
    errors.push({ contract: name, name: error.name, signature: error.format("sighash"), selector: error.selector });
  });
}

await writeFile(path.join(abiDir, "interface.json"), `${JSON.stringify({ events, errors }, null, 2)}\n`);
await writeFile(path.join(frontendDir, "abis.ts"), tsAbis.join("\n"));

const localManifestPath = path.join(DEPLOYMENTS_DIR, "localhost.json");
const localContracts: Record<string, string> = {};
if (existsSync(localManifestPath)) {
  const manifest = JSON.parse(await readFile(localManifestPath, "utf8")) as DeploymentManifest;
  for (const name of CONTRACT_NAMES) {
    localContracts[camel(name)] = manifest.contracts[name].address;
  }
}
await writeFile(
  path.join(frontendDir, "localDeployment.ts"),
  [
    `// ${HEADER}`,
    "// Deterministic addresses of a fresh `npm run deploy:local` on chain 31337. Never used for Sepolia.",
    `export const localDeployment = ${JSON.stringify({ chainId: 31337, contracts: localContracts }, null, 2)} as const;`,
    "",
  ].join("\n"),
);

const topicLines = events.map((event) => `    "${event.contract}.${event.name}": "${event.topic}",`);
await writeFile(
  backendFile,
  [
    `"""Contract event topics for receipt verification.`,
    "",
    `${HEADER}`,
    `"""`,
    "",
    "EVENT_TOPICS: dict[str, str] = {",
    ...topicLines,
    "}",
    "",
  ].join("\n"),
);

console.log(`Exported ${CONTRACT_NAMES.length} ABIs, ${events.length} event topics, ${errors.length} error selectors.`);
console.log(`  ${path.relative(REPO_ROOT, abiDir)}`);
console.log(`  ${path.relative(REPO_ROOT, frontendDir)}`);
console.log(`  ${path.relative(REPO_ROOT, backendFile)}`);
